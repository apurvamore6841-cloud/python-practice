#monthly sales list example:
monthly_sales = [12000, 15000, 9800, 17500, 14200, 16800]

print("Total:", sum(monthly_sales))
print(f"Average: {sum(monthly_sales) / len(monthly_sales):.2f}")
print("Highest:", max(monthly_sales))
print("Lowest:", min(monthly_sales))
print("Months:", len(monthly_sales))